"""Render adapters from reviewed source. Python 3.11+, no external packages."""
from pathlib import Path
import argparse
import json
import sys

ROOT = Path(__file__).resolve().parents[1]


def outputs(root=ROOT):
    common = (root / "agent-kit/common.md").read_text(encoding="utf-8")
    roles = json.loads((root / "agent-kit/catalog.json").read_text(encoding="utf-8"))["roles"]
    result = {}
    for role in roles:
        role_id = role["id"]
        body = common + "\n" + (root / f"agent-kit/roles/{role_id}.md").read_text(encoding="utf-8")
        header = {
            "name": role_id,
            "description": role["label"] + " — " + role["description"],
            "target": "github-copilot",
            "user-invocable": role["parent"],
            "disable-model-invocation": role["parent"],
            "tools": role["tools"],
        }
        yaml = "\n".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in header.items())
        result[f".github/agents/{role_id}.agent.md"] = "---\n" + yaml + "\n---\n\n<!-- Generated by tools/render.py; edit agent-kit instead. -->\n\n" + body
        # TOML adapters are worker definitions, not a parent-agent picker.
        if not role["parent"]:
            result[f".codex/agents/{role_id}.toml"] = (
                "# Generated by tools/render.py; edit agent-kit instead.\n"
                f"name = {json.dumps(role_id)}\n"
                f"description = {json.dumps(role['description'], ensure_ascii=False)}\n"
                f"developer_instructions = {json.dumps(body, ensure_ascii=False)}\n"
                "\n[features]\nshell_tool = false\n"
            )
    for path in sorted((root / ".agents/skills").rglob("*")):
        if path.is_file():
            result[str(Path(".github/skills") / path.relative_to(root / ".agents/skills"))] = path.read_text(encoding="utf-8")
    result[".github/copilot-instructions.md"] = (
        "<!-- Generated by tools/render.py. -->\n"
        "# 共通方針\n\nこのリポジトリの AGENTS.md を読み、その変更範囲・根拠・機密情報のルールに従う。\n"
        "Agent固有の役割は選択したAgent定義に従う。生成ファイルを直接編集しない。\n"
    )
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = outputs()
    stale = []
    for relative, content in generated.items():
        path = ROOT / relative
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    # Never silently remove user files or stale definitions after a role rename.
    extras = []
    for directory in (".github/agents", ".codex/agents", ".github/skills"):
        folder = ROOT / directory
        if folder.exists():
            extras += [str(p.relative_to(ROOT)) for p in folder.rglob("*") if p.is_file() and str(p.relative_to(ROOT)) not in generated]
    if extras:
        print("Unexpected adapter files; review manually:", *extras, sep="\n")
        return 1
    if args.check and stale:
        print("Generated files differ:", *stale, sep="\n")
        return 1
    print(f"{'Checked' if args.check else 'Rendered'} {len(generated)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
